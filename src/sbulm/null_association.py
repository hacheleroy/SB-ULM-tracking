"""Exact small-problem posterior with missed detections and Poisson clutter."""

from __future__ import annotations

from dataclasses import dataclass
from itertools import product
from math import log, pi, prod

import numpy as np
from numpy.typing import ArrayLike, NDArray
from scipy.linalg import cho_factor, cho_solve
from scipy.special import logsumexp

from .data import DetectionSequence
from .localization import _validate_localization_std
from .smooth_sb import matern_covariance

FloatArray = NDArray[np.float64]
IntArray = NDArray[np.int64]


def enumerate_frame_null_associations(n_particles: int, n_detections: int) -> IntArray:
    """Enumerate partial injections from particles to detections.

    Each particle is assigned either a unique detection index or ``-1``. A
    detection absent from the resulting vector is interpreted as clutter.
    """

    if n_particles < 1:
        raise ValueError("n_particles must be positive")
    if n_detections < 0:
        raise ValueError("n_detections must be non-negative")

    states: list[tuple[int, ...]] = []

    def extend(prefix: tuple[int, ...], used: frozenset[int]) -> None:
        if len(prefix) == n_particles:
            states.append(prefix)
            return
        extend((*prefix, -1), used)
        for detection in range(n_detections):
            if detection not in used:
                extend((*prefix, detection), used | {detection})

    extend((), frozenset())
    return np.asarray(states, dtype=np.int64)


@dataclass(frozen=True)
class NullAssociationPosterior:
    """Normalized posterior over partial association paths."""

    associations: IntArray
    log_probabilities: FloatArray
    probabilities: FloatArray

    def __post_init__(self) -> None:
        if self.associations.ndim != 3:
            raise ValueError("associations must have shape (H, T, N)")
        n_hypotheses = self.associations.shape[0]
        if self.log_probabilities.shape != (n_hypotheses,):
            raise ValueError("log_probabilities has the wrong shape")
        if self.probabilities.shape != (n_hypotheses,):
            raise ValueError("probabilities has the wrong shape")
        if np.any(self.probabilities < 0) or not np.isclose(np.sum(self.probabilities), 1.0):
            raise ValueError("probabilities must be non-negative and sum to one")

    @property
    def map_index(self) -> int:
        return int(np.argmax(self.probabilities))

    @property
    def normalized_entropy(self) -> float:
        positive = self.probabilities[self.probabilities > 0]
        entropy = -float(np.sum(positive * np.log(positive)))
        return 0.0 if self.probabilities.size <= 1 else entropy / log(self.probabilities.size)

    def credible_set_size(self, mass: float = 0.95) -> int:
        if not 0 < mass <= 1:
            raise ValueError("mass must lie in (0, 1]")
        ordered = np.sort(self.probabilities)[::-1]
        return int(np.searchsorted(np.cumsum(ordered), mass, side="left") + 1)


class NullAssociationMaternModel:
    r"""Collapsed Matérn model with an explicit null association.

    There are still a known number of latent bubbles. At every frame, a
    bubble either produces one localization with probability ``p_D`` or is
    missed and receives association ``-1``. Non-null associations are
    injective. Any unassigned localization is generated by a spatially
    uniform Poisson clutter process with mean ``lambda_c`` per frame.

    The implemented finite-set likelihood for an association ``a`` is

    .. math::

       e^{-T\lambda_c}
       p_D^{n_A}(1-p_D)^{NT-n_A}
       (\lambda_c/|R|)^{n_C}
       \prod_{i,d} p(y_{a_i,d}),

    where the final factors analytically integrate each Matérn path using only
    the times at which that bubble is assigned a detection. No clutter
    factorial appears because this is the standard Poisson point-process set
    density rather than a density over an ordered list.
    """

    def __init__(
        self,
        sequence: DetectionSequence,
        *,
        n_particles: int,
        localization_std: float,
        coordinate_std: ArrayLike,
        length_scale: float,
        detection_probability: float,
        expected_clutter_per_frame: float,
        roi_lower: ArrayLike,
        roi_upper: ArrayLike,
        nu: float = 1.5,
        relative_jitter: float = 1e-10,
        anchor_first_frame: bool = True,
    ) -> None:
        _validate_localization_std(localization_std)
        if n_particles < 1:
            raise ValueError("n_particles must be positive")
        if length_scale <= 0 or not np.isfinite(length_scale):
            raise ValueError("length_scale must be finite and positive")
        if not 0 < detection_probability < 1:
            raise ValueError("detection_probability must lie strictly between zero and one")
        if expected_clutter_per_frame <= 0 or not np.isfinite(expected_clutter_per_frame):
            raise ValueError("expected_clutter_per_frame must be finite and positive")
        if sequence.n_frames < 2:
            raise ValueError("at least two frames are required")
        if relative_jitter < 0 or not np.isfinite(relative_jitter):
            raise ValueError("relative_jitter must be finite and non-negative")

        coordinate_scales = np.asarray(coordinate_std, dtype=float)
        if coordinate_scales.shape != (sequence.dimension,):
            raise ValueError("coordinate_std must have one value per spatial dimension")
        if np.any(coordinate_scales <= 0) or not np.all(np.isfinite(coordinate_scales)):
            raise ValueError("each coordinate standard deviation must be finite and positive")
        lower = np.asarray(roi_lower, dtype=float)
        upper = np.asarray(roi_upper, dtype=float)
        if lower.shape != (sequence.dimension,) or upper.shape != lower.shape:
            raise ValueError("ROI bounds must match the spatial dimension")
        if not np.all(np.isfinite(lower)) or not np.all(np.isfinite(upper)):
            raise ValueError("ROI bounds must be finite")
        if np.any(upper <= lower):
            raise ValueError("every ROI upper bound must exceed its lower bound")
        if any(np.any(frame < lower) or np.any(frame > upper) for frame in sequence.detections):
            raise ValueError("the ROI must contain every observed detection")
        if anchor_first_frame and sequence.cardinalities[0] != n_particles:
            raise ValueError(
                "the anchored first frame must contain exactly one detection per particle"
            )

        self.sequence = sequence
        self.n_particles = int(n_particles)
        self.localization_std = float(localization_std)
        self.coordinate_std = coordinate_scales
        self.length_scale = float(length_scale)
        self.detection_probability = float(detection_probability)
        self.expected_clutter_per_frame = float(expected_clutter_per_frame)
        self.roi_lower = lower
        self.roi_upper = upper
        self.roi_volume = float(np.prod(upper - lower))
        self.clutter_intensity = self.expected_clutter_per_frame / self.roi_volume
        self.nu = float(nu)
        self.relative_jitter = float(relative_jitter)
        self.anchor_first_frame = bool(anchor_first_frame)

        self._prior_covariances: list[FloatArray] = []
        self._observation_cache: list[
            dict[tuple[int, ...], tuple[tuple[np.ndarray, bool], float]]
        ] = []
        self._conditional_cache: list[dict[tuple[int, ...], tuple[FloatArray, FloatArray]]] = []
        for coordinate_scale in coordinate_scales:
            variance = float(coordinate_scale**2)
            covariance = matern_covariance(
                sequence.times,
                variance=variance,
                length_scale=length_scale,
                nu=nu,
            )
            covariance.flat[:: sequence.n_frames + 1] += relative_jitter * variance
            self._prior_covariances.append(np.asarray(covariance, dtype=float))
            self._observation_cache.append({})
            self._conditional_cache.append({})

        frame_states: list[IntArray] = []
        frame_log_count_weights: list[FloatArray] = []
        for time_index, cardinality in enumerate(sequence.cardinalities):
            if time_index == 0 and anchor_first_frame:
                states = np.arange(n_particles, dtype=np.int64)[None, :]
            else:
                states = enumerate_frame_null_associations(n_particles, cardinality)
            assigned = np.count_nonzero(states >= 0, axis=1)
            clutter = cardinality - assigned
            log_weights = (
                assigned * log(self.detection_probability)
                + (n_particles - assigned) * log(1.0 - self.detection_probability)
                + clutter * log(self.clutter_intensity)
            )
            frame_states.append(states)
            frame_log_count_weights.append(np.asarray(log_weights, dtype=float))
        self._frame_states = tuple(frame_states)
        self._frame_log_count_weights = tuple(frame_log_count_weights)
        self._frame_log_normalizers = np.asarray(
            [logsumexp(weights) for weights in frame_log_count_weights], dtype=float
        )

    @property
    def base_log_normalizer(self) -> float:
        """Log sum of count weights, including the Poisson void factor."""

        return float(
            np.sum(self._frame_log_normalizers)
            - self.sequence.n_frames * self.expected_clutter_per_frame
        )

    def frame_states(self, time_index: int) -> IntArray:
        """Return all valid partial associations for one frame."""

        return self._frame_states[time_index].copy()

    def frame_log_count_weights(self, time_index: int) -> FloatArray:
        """Return unnormalized detection/clutter weights for one frame."""

        return self._frame_log_count_weights[time_index].copy()

    def _validate_associations(self, associations: ArrayLike) -> IntArray:
        raw = np.asarray(associations)
        expected = (self.sequence.n_frames, self.n_particles)
        if raw.ndim != 3 or raw.shape[1:] != expected:
            raise ValueError(f"associations must have shape (S, {expected[0]}, {expected[1]})")
        if not np.issubdtype(raw.dtype, np.integer):
            raise ValueError("associations must contain integer detection indices")
        integer = raw.astype(np.int64, copy=False)
        for time_index, cardinality in enumerate(self.sequence.cardinalities):
            frame = integer[:, time_index]
            if np.any(frame < -1) or np.any(frame >= cardinality):
                raise ValueError("an association contains an invalid detection index")
            for first in range(self.n_particles):
                for second in range(first + 1, self.n_particles):
                    duplicate = (
                        (frame[:, first] >= 0)
                        & (frame[:, second] >= 0)
                        & (frame[:, first] == frame[:, second])
                    )
                    if np.any(duplicate):
                        raise ValueError("non-null associations must be injective")
        if self.anchor_first_frame and not np.all(
            integer[:, 0] == np.arange(self.n_particles, dtype=np.int64)
        ):
            raise ValueError("the first-frame association must fix particle labels")
        return integer

    def log_count_density(
        self, associations: ArrayLike, *, include_poisson_void: bool = True
    ) -> FloatArray:
        """Score detection, missed-detection, and clutter-count factors."""

        integer = self._validate_associations(associations)
        assigned = np.count_nonzero(integer >= 0, axis=(1, 2))
        missed = self.sequence.n_frames * self.n_particles - assigned
        clutter = sum(self.sequence.cardinalities) - assigned
        scores = (
            assigned * log(self.detection_probability)
            + missed * log(1.0 - self.detection_probability)
            + clutter * log(self.clutter_intensity)
        )
        if include_poisson_void:
            scores = scores - (self.sequence.n_frames * self.expected_clutter_per_frame)
        return np.asarray(scores, dtype=float)

    def log_base_probability(self, associations: ArrayLike) -> FloatArray:
        """Return the normalized frame-factorized SMC base density."""

        scores = self.log_count_density(associations, include_poisson_void=False)
        return scores - float(np.sum(self._frame_log_normalizers))

    def sample_base_associations(self, *, n_samples: int, rng: np.random.Generator) -> IntArray:
        """Draw exact samples from the normalized count-only base density."""

        if n_samples < 1:
            raise ValueError("n_samples must be positive")
        associations = np.empty(
            (n_samples, self.sequence.n_frames, self.n_particles), dtype=np.int64
        )
        for time_index, (states, log_weights) in enumerate(
            zip(self._frame_states, self._frame_log_count_weights, strict=True)
        ):
            probabilities = np.exp(log_weights - logsumexp(log_weights))
            selected = rng.choice(states.shape[0], size=n_samples, p=probabilities)
            associations[:, time_index] = states[selected]
        return associations

    def _observation_factor(
        self, dimension: int, observed_times: tuple[int, ...]
    ) -> tuple[tuple[np.ndarray, bool], float]:
        cached = self._observation_cache[dimension].get(observed_times)
        if cached is not None:
            return cached
        covariance = self._prior_covariances[dimension]
        indices = np.asarray(observed_times, dtype=np.int64)
        observed_covariance = covariance[np.ix_(indices, indices)].copy()
        observed_covariance.flat[:: indices.size + 1] += self.localization_std**2
        factor = cho_factor(observed_covariance, lower=True, check_finite=False)
        log_determinant = 2.0 * float(np.sum(np.log(np.diag(factor[0]))))
        log_normalizer = indices.size * log(2.0 * pi) + log_determinant
        cached = (factor, log_normalizer)
        self._observation_cache[dimension][observed_times] = cached
        return cached

    def _assigned_coordinates(
        self,
        associations: IntArray,
        sample_indices: IntArray,
        observed_times: tuple[int, ...],
        *,
        particle: int,
        dimension: int,
    ) -> FloatArray:
        coordinates = np.empty((len(observed_times), sample_indices.size), dtype=float)
        for row, time_index in enumerate(observed_times):
            detection_indices = associations[sample_indices, time_index, particle]
            coordinates[row] = self.sequence.detections[time_index][detection_indices, dimension]
        return coordinates

    def log_marginal_density(self, associations: ArrayLike) -> FloatArray:
        """Integrate latent paths and score only assigned localizations."""

        integer = self._validate_associations(associations)
        scores = np.zeros(integer.shape[0], dtype=float)
        for particle in range(self.n_particles):
            observed = integer[:, :, particle] >= 0
            patterns, inverse = np.unique(observed, axis=0, return_inverse=True)
            for pattern_index, pattern in enumerate(patterns):
                observed_times = tuple(int(value) for value in np.flatnonzero(pattern))
                if not observed_times:
                    continue
                sample_indices = np.flatnonzero(inverse == pattern_index).astype(np.int64)
                for dimension in range(self.sequence.dimension):
                    factor, log_normalizer = self._observation_factor(dimension, observed_times)
                    coordinates = self._assigned_coordinates(
                        integer,
                        sample_indices,
                        observed_times,
                        particle=particle,
                        dimension=dimension,
                    )
                    solved = cho_solve(factor, coordinates, check_finite=False)
                    quadratics = np.sum(coordinates * solved, axis=0)
                    scores[sample_indices] -= 0.5 * (quadratics + log_normalizer)
        return scores

    def log_joint_density(self, associations: ArrayLike) -> FloatArray:
        """Return the full unnormalized finite-set association log density."""

        return self.log_count_density(associations) + self.log_marginal_density(associations)

    def _conditional_parameters(
        self, dimension: int, observed_times: tuple[int, ...]
    ) -> tuple[FloatArray, FloatArray]:
        cached = self._conditional_cache[dimension].get(observed_times)
        if cached is not None:
            return cached
        covariance = self._prior_covariances[dimension]
        if observed_times:
            indices = np.asarray(observed_times, dtype=np.int64)
            factor, _ = self._observation_factor(dimension, observed_times)
            cross_covariance = covariance[:, indices]
            gain = cho_solve(factor, cross_covariance.T, check_finite=False).T
            conditional_covariance = covariance - gain @ cross_covariance.T
        else:
            gain = np.empty((self.sequence.n_frames, 0), dtype=float)
            conditional_covariance = covariance.copy()
        conditional_covariance = 0.5 * (conditional_covariance + conditional_covariance.T)
        scale = max(float(np.max(np.diag(conditional_covariance))), np.finfo(float).tiny)
        conditional_covariance.flat[:: self.sequence.n_frames + 1] += self.relative_jitter * scale
        cached = (gain, np.linalg.cholesky(conditional_covariance))
        self._conditional_cache[dimension][observed_times] = cached
        return cached

    def conditional_path_means(self, associations: ArrayLike) -> FloatArray:
        """Return the Matérn conditional mean for every partial association."""

        integer = self._validate_associations(associations)
        means = np.zeros((*integer.shape, self.sequence.dimension), dtype=float)
        for particle in range(self.n_particles):
            observed = integer[:, :, particle] >= 0
            patterns, inverse = np.unique(observed, axis=0, return_inverse=True)
            for pattern_index, pattern in enumerate(patterns):
                observed_times = tuple(int(value) for value in np.flatnonzero(pattern))
                sample_indices = np.flatnonzero(inverse == pattern_index).astype(np.int64)
                if not observed_times:
                    continue
                for dimension in range(self.sequence.dimension):
                    gain, _ = self._conditional_parameters(dimension, observed_times)
                    coordinates = self._assigned_coordinates(
                        integer,
                        sample_indices,
                        observed_times,
                        particle=particle,
                        dimension=dimension,
                    )
                    means[sample_indices, :, particle, dimension] = (gain @ coordinates).T
        return means

    def sample_conditional_paths(
        self, associations: ArrayLike, *, rng: np.random.Generator
    ) -> FloatArray:
        r"""Draw full paths from :math:`p(x\mid y,a)` despite missing frames."""

        integer = self._validate_associations(associations)
        paths = np.empty((*integer.shape, self.sequence.dimension), dtype=float)
        for particle in range(self.n_particles):
            observed = integer[:, :, particle] >= 0
            patterns, inverse = np.unique(observed, axis=0, return_inverse=True)
            for pattern_index, pattern in enumerate(patterns):
                observed_times = tuple(int(value) for value in np.flatnonzero(pattern))
                sample_indices = np.flatnonzero(inverse == pattern_index).astype(np.int64)
                for dimension in range(self.sequence.dimension):
                    gain, cholesky = self._conditional_parameters(dimension, observed_times)
                    if observed_times:
                        coordinates = self._assigned_coordinates(
                            integer,
                            sample_indices,
                            observed_times,
                            particle=particle,
                            dimension=dimension,
                        )
                        conditional_mean = gain @ coordinates
                    else:
                        conditional_mean = np.zeros(
                            (self.sequence.n_frames, sample_indices.size), dtype=float
                        )
                    innovations = cholesky @ rng.standard_normal(conditional_mean.shape)
                    paths[sample_indices, :, particle, dimension] = (
                        conditional_mean + innovations
                    ).T
        return paths


def enumerate_null_association_support(
    model: NullAssociationMaternModel,
    *,
    max_hypotheses: int = 250_000,
) -> IntArray:
    """Enumerate every valid anchored partial association path."""

    frame_states = tuple(model.frame_states(index) for index in range(model.sequence.n_frames))
    n_hypotheses = prod(states.shape[0] for states in frame_states)
    if n_hypotheses > max_hypotheses:
        raise ValueError(
            f"enumeration would create {n_hypotheses:,} hypotheses; "
            "increase max_hypotheses deliberately or use the SMC sampler"
        )
    associations = np.empty(
        (n_hypotheses, model.sequence.n_frames, model.n_particles), dtype=np.int64
    )
    for hypothesis, state_indices in enumerate(
        product(*(range(states.shape[0]) for states in frame_states))
    ):
        for time_index, state_index in enumerate(state_indices):
            associations[hypothesis, time_index] = frame_states[time_index][state_index]
    return associations


def enumerate_null_association_posterior(
    sequence: DetectionSequence,
    *,
    n_particles: int,
    localization_std: float,
    coordinate_std: ArrayLike,
    length_scale: float,
    detection_probability: float,
    expected_clutter_per_frame: float,
    roi_lower: ArrayLike,
    roi_upper: ArrayLike,
    nu: float = 1.5,
    relative_jitter: float = 1e-10,
    anchor_first_frame: bool = True,
    max_hypotheses: int = 250_000,
) -> NullAssociationPosterior:
    """Exactly enumerate the missed-detection/clutter association posterior."""

    model = NullAssociationMaternModel(
        sequence,
        n_particles=n_particles,
        localization_std=localization_std,
        coordinate_std=coordinate_std,
        length_scale=length_scale,
        detection_probability=detection_probability,
        expected_clutter_per_frame=expected_clutter_per_frame,
        roi_lower=roi_lower,
        roi_upper=roi_upper,
        nu=nu,
        relative_jitter=relative_jitter,
        anchor_first_frame=anchor_first_frame,
    )
    associations = enumerate_null_association_support(model, max_hypotheses=max_hypotheses)
    log_scores = model.log_joint_density(associations)
    normalized = log_scores - logsumexp(log_scores)
    return NullAssociationPosterior(
        associations=associations,
        log_probabilities=normalized,
        probabilities=np.exp(normalized),
    )


def reference_null_association(sequence: DetectionSequence, *, n_particles: int) -> IntArray:
    """Recover the simulated partial association, using ``-1`` for misses."""

    if sequence.reference_ids is None:
        raise ValueError("reference_ids are required")
    association = np.full((sequence.n_frames, n_particles), -1, dtype=np.int64)
    for time_index, frame_ids in enumerate(sequence.reference_ids):
        for detection_index, identity in enumerate(frame_ids):
            if identity < 0:
                continue
            if identity >= n_particles:
                raise ValueError("a reference ID exceeds n_particles")
            if association[time_index, identity] >= 0:
                raise ValueError("a frame contains a duplicate reference ID")
            association[time_index, identity] = detection_index
    return association


def null_and_clutter_marginals(
    associations: ArrayLike,
    sequence: DetectionSequence,
    *,
    probabilities: ArrayLike | None = None,
) -> tuple[FloatArray, FloatArray]:
    """Return null probabilities and expected clutter counts by frame."""

    integer = np.asarray(associations)
    if integer.ndim != 3 or integer.shape[1] != sequence.n_frames:
        raise ValueError("associations must have shape (S, T, N)")
    if integer.shape[0] == 0:
        raise ValueError("at least one association sample is required")
    if probabilities is None:
        weights = np.full(integer.shape[0], 1.0 / integer.shape[0])
    else:
        weights = np.asarray(probabilities, dtype=float)
        if weights.shape != (integer.shape[0],):
            raise ValueError("probabilities has the wrong shape")
        if np.any(weights < 0) or not np.isclose(np.sum(weights), 1.0):
            raise ValueError("probabilities must be non-negative and sum to one")
    null_probabilities = np.tensordot(weights, integer < 0, axes=(0, 0))
    assigned_counts = np.count_nonzero(integer >= 0, axis=2)
    cardinalities = np.asarray(sequence.cardinalities, dtype=float)
    expected_clutter = cardinalities - np.tensordot(weights, assigned_counts, axes=(0, 0))
    return (
        np.asarray(null_probabilities, dtype=float),
        np.asarray(expected_clutter, dtype=float),
    )
